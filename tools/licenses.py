"""Generate docs/THIRD_PARTY_LICENSES.md from the real dependency trees:
Python (backend venv, runtime packages only), npm (production dependencies), Rust (cargo metadata)."""
from __future__ import annotations
import json, subprocess, sys
from importlib import metadata
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RUNTIME_PY = {"python-docx", "docxtpl", "lxml", "pypdf", "PyYAML", "keyring", "jinja2", "markupsafe", "typing_extensions",
              "jaraco.classes", "jaraco.context", "jaraco.functools", "more-itertools", "importlib_metadata", "zipp", "backports.tarfile", "docxcompose"}
DEV_ONLY_NOTE = {"PyInstaller": "GPL-2.0 with bootloader exception: build tool only; produced executables are not GPL",
                 "LibreOffice": "MPL-2.0: installed separately by the user, not bundled", "poppler": "GPL: developer fidelity tests only, never shipped"}


def py_rows():
    rows = []
    for dist in metadata.distributions():
        name = dist.metadata["Name"]
        if name not in RUNTIME_PY and name.lower() not in {n.lower() for n in RUNTIME_PY}:
            continue
        lic = dist.metadata.get("License-Expression") or dist.metadata.get("License") or ""
        if not lic or len(lic) > 40:
            lic = next((c.split("::")[-1].strip() for c in (dist.metadata.get_all("Classifier") or []) if c.startswith("License ::")), lic[:40])
        rows.append((name, dist.version, lic or "see package"))
    return sorted(rows, key=lambda r: r[0].lower())


def npm_rows():
    out = subprocess.run(["npm", "ls", "--omit=dev", "--all", "--json", "--long"], cwd=ROOT / "apps/desktop", capture_output=True, text=True).stdout
    tree = json.loads(out or "{}"); rows = {}
    def walk(deps):
        for name, d in (deps or {}).items():
            rows[name] = (d.get("version", "?"), d.get("license", "?") if isinstance(d.get("license"), str) else "see package")
            walk(d.get("dependencies"))
    walk(tree.get("dependencies"))
    return sorted((n, v, l) for n, (v, l) in rows.items())


def rust_rows():
    out = subprocess.run(["cargo", "metadata", "--format-version", "1", "--locked"], cwd=ROOT / "apps/desktop/src-tauri", capture_output=True, text=True).stdout
    meta = json.loads(out); rows = []
    for p in meta["packages"]:
        if p["name"] == "papyra": continue
        rows.append((p["name"], p["version"], p.get("license") or "see crate"))
    return sorted(set(rows))


def main():
    py, npm, rs = py_rows(), npm_rows(), rust_rows()
    lines = ["# Third-party licenses", "", "Generated by `tools/licenses.py`. Papyra bundles the components below; each remains under its own license.", ""]
    for title, rows in (("Python backend (bundled in the sidecar)", py), ("JavaScript (bundled in the UI)", npm), ("Rust crates (compiled into the desktop shell)", rs)):
        lines += [f"## {title}", "", "| Package | Version | License |", "|---|---|---|"] + [f"| {n} | {v} | {l} |" for n, v, l in rows] + [""]
    lines += ["## Build-time and external components (not redistributed)", "", "| Component | Note |", "|---|---|"] + [f"| {k} | {v} |" for k, v in DEV_ONLY_NOTE.items()] + [""]
    flagged = [r for r in py + npm + rs if any(x in (r[2] or "") for x in ("GPL", "AGPL")) and "LGPL" not in (r[2] or "")]
    lines += ["## Copyleft check", "", "Packages with GPL/AGPL licenses would require source disclosure; none are bundled." if not flagged else "**Review required:** " + ", ".join(f"{n} ({l})" for n, _, l in flagged), "",
              "docxtpl is LGPL-2.1: it is shipped as replaceable bytecode inside the one-dir backend folder, which satisfies the LGPL relinking requirement.", ""]
    (ROOT / "docs/THIRD_PARTY_LICENSES.md").write_text("\n".join(lines))
    print(f"python {len(py)}, npm {len(npm)}, rust {len(rs)}; flagged: {[n for n, _, _ in flagged]}")


if __name__ == "__main__":
    sys.exit(main())
