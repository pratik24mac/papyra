"""Scaffold a bundled template from a Word file you tagged yourself — nothing leaves your machine.

    .venv/bin/python tools/new_template.py <template-id> <path/to/tagged.docx> --name "Display name" [--description "..."]

Steps performed:
  1. copies the .docx to templates/<id>/v1/template.docx (your original is not modified)
  2. finds every {{ variable }} in it and writes a schema.yaml skeleton (edit labels/types/required)
  3. writes values.example.yaml with placeholder values so you can test-render immediately
  4. runs the linter and prints what to fix
Then:  .venv/bin/python tools/render_template.py templates/<id>/v1 templates/<id>/v1/values.example.yaml out.docx
"""
from __future__ import annotations
import argparse, re, shutil, sys
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "backend"))
import yaml
from docxtpl import DocxTemplate
from jinja2 import Environment, StrictUndefined
from docmaster.docgen.linter import lint_template  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]


def guess_type(var: str) -> str:
    v = var.lower()
    if v.endswith("_url") or v in ("website", "linkedin", "github"): return "url"
    if "email" in v: return "email"
    if v.endswith(("_date", "date")): return "date"
    if any(k in v for k in ("summary", "description", "body", "message", "address", "notes", "clause", "text")): return "multiline"
    if any(k in v for k in ("amount", "count", "number_of", "qty", "years")): return "number"
    return "text"


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("template_id", help="lowercase id with dashes, e.g. employment-contract")
    ap.add_argument("docx", type=Path)
    ap.add_argument("--name", required=True)
    ap.add_argument("--description", default="")
    ap.add_argument("--version", type=int, default=1)
    ap.add_argument("--force", action="store_true", help="overwrite an existing template folder")
    a = ap.parse_args()
    if not re.fullmatch(r"[a-z0-9][a-z0-9-]{1,40}", a.template_id):
        ap.error("template id must be lowercase letters, digits and dashes")
    if not a.docx.exists():
        ap.error(f"{a.docx} not found")
    dest = ROOT / "templates" / a.template_id / f"v{a.version}"
    if dest.exists() and not a.force:
        ap.error(f"{dest} exists; use --force to overwrite")
    dest.mkdir(parents=True, exist_ok=True)
    shutil.copy(a.docx, dest / "template.docx")

    tpl = DocxTemplate(dest / "template.docx")
    used = sorted(tpl.get_undeclared_template_variables(Environment(undefined=StrictUndefined, autoescape=True)))
    if not used:
        print("WARNING: no {{ tags }} found in the document. Add placeholders in Word first (see docs/template-authoring-guide.md).")
    fields, example = [], {}
    # {{r x_link }} tags are produced automatically from a url field `x_url`
    wanted = [v for v in used if not v.endswith("_link")] + [v[:-5] + "_url" for v in used if v.endswith("_link") and v[:-5] + "_url" not in used]
    for var in wanted:
        t = guess_type(var)
        label = var.replace("_", " ").capitalize()
        f = {"id": var, "label": label, "type": t, "required": True}
        if t in ("text", "multiline"): f["validation"] = {"max_length": 2000 if t == "multiline" else 200}
        fields.append(f)
        example[var] = {"url": "https://example.com", "email": "someone@example.com", "date": "2026-01-31", "number": 1,
                        "multiline": f"Sample {label.lower()} text.\nSecond line."}.get(t, f"Sample {label.lower()}")
    schema = {
        "template": {"id": a.template_id, "version": a.version, "name": a.name, "description": a.description,
                     "file": "template.docx", "output_filename": "{" + (used[0] if used else "date") + "}-" + a.name.replace(" ", "-") + "-{date}",
                     "expected_pages": {"min": 1, "max": 10}, "essential_text": used[:1]},
        "groups": [
            {"id": "details", "label": "Details", "fields": fields},
            {"id": "email_draft", "label": "Email draft", "print": False, "fields": [
                {"id": "recipient_email", "label": "Recipient", "type": "email", "required": True},
                {"id": "email_subject", "label": "Subject", "type": "text", "required": True, "default": a.name},
                {"id": "email_body", "label": "Message", "type": "multiline", "required": True, "default": "Please find the document attached."},
            ]},
        ],
    }
    (dest / "schema.yaml").write_text("# Generated by tools/new_template.py — edit labels, types, required flags, groups.\n"
                                      + yaml.safe_dump(schema, allow_unicode=True, sort_keys=False), encoding="utf8")
    example.update({"recipient_email": "someone@example.com", "email_subject": a.name, "email_body": "Please find the document attached."})
    (dest / "values.example.yaml").write_text(yaml.safe_dump(example, allow_unicode=True, sort_keys=False), encoding="utf8")

    print(f"created {dest}\n  variables found: {used or 'none'}")
    findings = lint_template(dest / "template.docx", schema)
    print("  lint:", "OK" if not findings else "")
    for x in findings: print("   ", x)
    print(f"\nnext: .venv/bin/python tools/render_template.py {dest.relative_to(ROOT)} {dest.relative_to(ROOT)}/values.example.yaml out.docx")
    return 1 if any(x.level == "error" for x in findings) else 0


if __name__ == "__main__":
    sys.exit(main())
